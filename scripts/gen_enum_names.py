#!/usr/bin/env python3
"""Generates the name tables of OpenVR enums (for the *NameFromEnum calls and VR_GetVRInitErrorAsSymbol) from an
OpenVR header.

  gen_enum_names.py <output .cpp> <header> [<older header>...]

Each enum is taken from the first header that has it (newer SDKs dropped some, EVRApplicationTransitionState say).

Produces const char* OC_EnumName(const char* enumType, int32_t value): the first name with that value, or nullptr.
"""

import re
import sys
from pathlib import Path

ENUMS = ["EVRInitError", "EVREventType", "EVRButtonId", "EVRControllerAxisType", "EVROverlayError",
         "EVRApplicationError", "EVRApplicationTransitionState", "EVRSceneApplicationState", "EVRInputError",
         "ETrackedPropertyError", "EVRSettingsError", "EVRRenderModelError", "EVRTrackedCameraError",
         "EVRCompositorError"]

ENUM_RE = re.compile(r"enum\s+(?:class\s+)?(\w+)\s*(?::\s*\w+)?\s*\{(.*?)\}\s*;", re.S)
ENTRY_RE = re.compile(r"^\s*(\w+)\s*(?:=\s*([^,]+?))?\s*,?\s*$")


def evaluate(expr, known):
    expr = expr.strip()
    m = re.fullmatch(r"\(?\s*(-?(?:0x[0-9a-fA-F]+|\d+))\s*<<\s*(\d+)\s*\)?", expr)
    if m:
        return int(m.group(1), 0) << int(m.group(2))
    m = re.fullmatch(r"-?(?:0x[0-9a-fA-F]+|\d+)", expr)
    if m:
        return int(expr, 0)
    if expr in known:
        return known[expr]
    m = re.fullmatch(r"(\w+)\s*\+\s*(\d+)", expr)
    if m and m.group(1) in known:
        return known[m.group(1)] + int(m.group(2))
    return None


def parse(text):
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    enums = {}
    for name, body in ENUM_RE.findall(text):
        if name not in ENUMS or name in enums:
            continue
        values, known, nxt = [], {}, 0
        for raw in body.split(","):
            raw = raw.strip()
            if not raw:
                continue
            m = ENTRY_RE.match(raw)
            if not m:
                continue
            entry, expr = m.group(1), m.group(2)
            value = nxt if expr is None else evaluate(expr, known)
            if value is None:
                continue
            known[entry] = value
            values.append((entry, value))
            nxt = value + 1
        enums[name] = values
    return enums


def main():
    out = Path(sys.argv[1])
    headers = [Path(h) for h in sys.argv[2:]]
    enums = {}
    for header in headers:
        for name, values in parse(header.read_text(encoding="latin-1")).items():
            enums.setdefault(name, values)
    lines = [f"// Generated by scripts/gen_enum_names.py from {', '.join(h.name for h in headers)}: do not edit.",
             '#include "Misc/EnumNames.h"', "", "#include <cstring>", "",
             "const char* OC_EnumName(const char* enumType, int32_t value)", "{",
             "\tif (!enumType)", "\t\treturn nullptr;"]
    for name in ENUMS:
        seen = set()
        lines.append(f'\tif (!std::strcmp(enumType, "{name}")) {{')
        lines.append("\t\tswitch (value) {")
        for entry, value in enums.get(name, []):
            if value in seen or not (-2**31 <= value < 2**31):
                continue
            seen.add(value)
            lines.append(f'\t\tcase {value}: return "{entry}";')
        lines.append("\t\tdefault: return nullptr;")
        lines.append("\t\t}")
        lines.append("\t}")
    lines += ["\treturn nullptr;", "}"]
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
    missing = [n for n in ENUMS if not enums.get(n)]
    if missing:
        print("enums not found:", ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
